%                 | "driven_flow" | "autonomous_flow" | "conservative_flow"
%     kind        "map" | "flow"
%     f           map:  v -> v_next.   flow: (t, v) -> dv/dt.
%     x0          initial condition, column vector
%     lambda      largest Lyapunov exponent, NATS per iteration or per unit
