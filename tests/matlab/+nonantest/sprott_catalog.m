% ---------------------------------------------------------------- builders

function s = mk(name, pretty, section, category, f, x0, lambda, tier)
s = struct('name', string(name), 'pretty', string(pretty), ...
    'section', string(section), 'category', string(category), ...
    'kind', "map", 'f', f, 'x0', x0(:), 'lambda', lambda, ...
    'tier', string(tier), 'obs', 1, 'dt', NaN, 'usable', true, 'note', "");
end

function s = mkf(name, pretty, section, category, f, x0, lambda, tier, dt)
s = struct('name', string(name), 'pretty', string(pretty), ...
    'section', string(section), 'category', string(category), ...
    'kind', "flow", 'f', f, 'x0', x0(:), 'lambda', lambda, ...
    'tier', string(tier), 'obs', 1, 'dt', dt, 'usable', true, 'note', "");
end

% ------------------------------------------------- systems needing helpers

function w = dissStd(v)
y = mod(0.1*v(2) + 8.8*sin(v(1)), 2*pi);
w = [mod(v(1) + y, 2*pi); y];
end

function w = ikeda(v)
phi = 0.4 - 6/(1 + v(1)^2 + v(2)^2);
w = [1 + 0.9*(v(1)*cos(phi) - v(2)*sin(phi)); 0.9*(v(1)*sin(phi) + v(2)*cos(phi))];
end

function w = chirikov(v)
y = mod(v(2) + 1*sin(v(1)), 2*pi);
w = [mod(v(1) + y, 2*pi); y];
end

function w = henonArea(v)
ca = 0.24; sa = sqrt(1 - ca^2);
w = [v(1)*ca - (v(2) - v(1)^2)*sa; v(1)*sa + (v(2) - v(1)^2)*ca];
end

function w = chaoticWeb(v)
al = pi/2;
w = [v(1)*cos(al) - (v(2) + 1*sin(v(1)))*sin(al); ...
     v(1)*sin(al) + (v(2) + 1*sin(v(1)))*cos(al)];
end

function d = chua(v)
% dx/dt = alpha[y - x + b*x + 0.5*(a-b)*(|x+1| - |x-1|)]
% The bracketed terms are ADDED, per the appendix. Subtracting them instead
% (treating b*x + ... as a nonlinearity to remove) drives the system to a
% fixed point: std of x falls to 7e-24 over 500 samples.
al = 9; be = 100/7; a = 8/7; b = 5/7;
h = b*v(1) + 0.5*(a - b)*(abs(v(1)+1) - abs(v(1)-1));
d = [al*(v(2) - v(1) + h); v(1) - v(2) + v(3); -be*v(2)];
end
